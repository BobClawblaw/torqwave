def find_chrome():
    candidates = [
        shutil.which("google-chrome"),
        shutil.which("chromium"),
        shutil.which("chromium-browser"),
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
    ]
    for c in candidates:
        if c and Path(c).exists():
            return c
    return None


def read_project_version():
    cm = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    m = re.search(r"^project\(Torqwave VERSION ([0-9.]+)", cm, re.M)
    if not m:
        sys.exit("Could not find project version in CMakeLists.txt")
    return m.group(1)


def load_snapshot(version):
    snap_path = SNAP_DIR / f"{version}.json"
    if not snap_path.exists():
        sys.exit(f"Snapshot not found: {snap_path}. Create it before running release_kit.py.")
    defs = json.loads((COMPARE_DIR / "data" / "comparison.json").read_text(encoding="utf-8"))
    snap = json.loads(snap_path.read_text(encoding="utf-8"))
    return defs, snap


def coverage_summary(defs, snap):
    rows = [r for g in defs["groups"] for r in g["rows"]]
    tq = snap["products"]["torqwave"]["cells"]
    prev = snap["products"].get("torqwave_prev", {}).get("cells", {})
    yes_now = sum(1 for r in rows if tq[r["id"]]["value"] == "yes")
    yes_prev = sum(1 for r in rows if prev.get(r["id"], {}).get("value") == "yes") if prev else yes_now
    new_rows = [r["title"] for r in rows if tq[r["id"]]["value"] == "yes" and prev.get(r["id"], {}).get("value") != "yes"]
    return yes_now, yes_prev, len(rows), new_rows


