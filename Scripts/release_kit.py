def export_plaintext_copy(ann_path, x_dir, ig_dir):
    """Extracts pure plaintext .txt files (zero Markdown) into x/ and instagram/ for instant Cmd-A/Cmd-C posting."""
    text = ann_path.read_text(encoding="utf-8")
    exported = []

    m_long = re.search(r"```long\n(.*?)```", text, re.S)
    if m_long:
        p = x_dir / "post-long.txt"
        p.write_text(m_long.group(1).strip() + "\n", encoding="utf-8")
        exported.append(p)
        print("wrote", p.relative_to(ROOT))

    threads = [b.strip() for b in re.findall(r"```text\n(.*?)```", text, re.S)]
    if threads:
        p = x_dir / "post-thread.txt"
        blocks = [f"--- POST {i} / {len(threads)} ---\n\n{t}" for i, t in enumerate(threads, 1)]
        p.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
        exported.append(p)
        print("wrote", p.relative_to(ROOT))

    m_ig = re.search(r"```instagram\n(.*?)```", text, re.S)
    if m_ig:
        p = ig_dir / "caption.txt"
        p.write_text(m_ig.group(1).strip() + "\n", encoding="utf-8")
        exported.append(p)
        print("wrote", p.relative_to(ROOT))

    return exported


def update_manifest(ver, defs, snap, rel_dir, x_files, ig_files, txt_files):
    yes_now, yes_prev, total, new_rows = coverage_summary(defs, snap)
    manifest_path = rel_dir / "manifest.json"
    existing = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    channels = existing.get("channels", {})
    channels.setdefault("github_release", {
        "published": True,
        "url": f"https://github.com/BobClawblaw/torqwave/releases/tag/v{ver}",
    })
    channels.setdefault("site", {
        "url": "https://bobclawblaw.github.io/torqwave/",
    })
    channels.setdefault("x", {
        "posted": False,
        "url": None,
        "notes": "Optional — drag files from x/ into X.com composer and paste x/post-long.txt (or x/post-thread.txt).",
    })
    channels.setdefault("instagram", {
        "posted": False,
        "url": None,
        "notes": "Optional — drag slide-1.png..slide-7.png from instagram/ and paste instagram/caption.txt.",
    })

    manifest = {
        "version": ver,
        "tag": f"v{ver}",
        "as_of": snap["as_of"],
        "previous_snapshot": snap["previous"],
        "matrix_coverage": {"yes": yes_now, "previous_yes": yes_prev, "total": total, "new_rows": new_rows},
        "assets": {
            "announcement": str((rel_dir / "ANNOUNCEMENT.md").relative_to(ROOT)),
            "plaintext_copy": [str(p.relative_to(ROOT)) for p in txt_files],
            "x_graphics": [str(p.relative_to(ROOT)) for p in x_files],
            "instagram_slides": [str(p.relative_to(ROOT)) for p in ig_files],
        },
        "channels": channels,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote", manifest_path.relative_to(ROOT))
    return manifest_path


def main():
    ap = argparse.ArgumentParser(description="Build Torqwave release marketing kit (X + Instagram + announcement + manifest).")
    ap.add_argument("--version", default=None, help="Release version (default: from CMakeLists.txt)")
    ap.add_argument("--force-announcement", action="store_true", help="Overwrite ANNOUNCEMENT.md even if it exists")
    ap.add_argument("--open", action="store_true", help="Open docs/releases/<version>/ in Finder on macOS")
    args = ap.parse_args()

    ver = args.version or read_project_version()
    defs, snap = load_snapshot(ver)

    print(f"== Generating comparison matrix & 1600x900 graphics for {ver}")
    subprocess.run([sys.executable, str(COMPARE_DIR / "generate.py")], check=True)

    rel_dir = RELEASES_DIR / ver
    x_dir = rel_dir / "x"
    ig_dir = rel_dir / "instagram"
    x_dir.mkdir(parents=True, exist_ok=True)
    ig_dir.mkdir(parents=True, exist_ok=True)

    print(f"== Staging X.com graphics -> {x_dir.relative_to(ROOT)}")
    x_files = stage_x_graphics(x_dir)

    print(f"== Building Instagram 1080x1350 carousel -> {ig_dir.relative_to(ROOT)}")
    slides_html, count = build_instagram_html(defs, snap, ig_dir)
    ig_files = render_instagram_slides(slides_html, count, ig_dir)

    ann_path = rel_dir / "ANNOUNCEMENT.md"
    if args.force_announcement or not ann_path.exists():
        write_default_announcement(ver, defs, snap, ann_path)
    else:
        print("kept existing", ann_path.relative_to(ROOT))

    print("== Verifying X.com thread lengths & alt texts")
    subprocess.run([sys.executable, str(COMPARE_DIR / "generate.py"), "--posts", str(ann_path)], check=True)

    txt_files = export_plaintext_copy(ann_path, x_dir, ig_dir)
    update_manifest(ver, defs, snap, rel_dir, x_files, ig_files, txt_files)

